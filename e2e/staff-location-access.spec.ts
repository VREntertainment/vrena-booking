import { expect, test } from '@playwright/test'
import { loginAsAdmin } from './support/admin'

test('employee location access supports multiple checkboxes and persists after reopening', async ({ page }, testInfo) => {
  test.skip(testInfo.project.name !== 'chromium', 'Use the isolated local employee fixture once.')
  if (process.env.SUPABASE_URL !== 'http://127.0.0.1:56431') throw new Error('This access test requires isolated services.')
  await loginAsAdmin(page)
  await page.goto('/hr')
  await expect(page.getByTestId('staff-console')).toBeVisible()
  const panel = page.getByRole('region', { name: 'Location access', exact: true })
  await expect(panel).toBeVisible()
  await panel.locator('summary').click()
  await panel.getByRole('checkbox', { name: 'VRena Hà Đô Centrosa', exact: true }).check()
  await panel.getByRole('checkbox', { name: 'VRena Thảo Điền', exact: true }).check()
  await panel.getByRole('button', { name: 'Save location access', exact: true }).click()
  await expect(panel.getByRole('status')).toHaveText('Location access saved.')
  await page.reload()
  await expect(panel).toBeVisible()
  await panel.locator('summary').click()
  await expect(panel.getByRole('checkbox', { name: 'VRena Hà Đô Centrosa', exact: true })).toBeChecked()
  await expect(panel.getByRole('checkbox', { name: 'VRena Thảo Điền', exact: true })).toBeChecked()
  await panel.getByRole('checkbox', { name: 'VRena Hà Đô Centrosa', exact: true }).uncheck()
  await panel.getByRole('button', { name: 'Save location access', exact: true }).click()
  await expect(panel.getByRole('status')).toHaveText('Location access saved.')
  await page.reload()
  await panel.locator('summary').click()
  await expect(panel.getByRole('checkbox', { name: 'VRena Hà Đô Centrosa', exact: true })).not.toBeChecked()
  await expect(panel.getByRole('checkbox', { name: 'VRena Thảo Điền', exact: true })).toBeChecked()
  await page.setViewportSize({ width: 375, height: 812 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
