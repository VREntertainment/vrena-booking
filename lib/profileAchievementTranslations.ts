export function localizeRetentionAchievement(
  achievement: RetentionAchievement,
  language: LanguageCode,
): RetentionAchievement {
  const localized = retentionAchievementText[language]?.[achievement.id]
  return localized ? { ...achievement, ...localized } : achievement
}

export function localizeMilestoneReward(
  reward: AchievementMilestoneReward,
  language: LanguageCode,
): AchievementMilestoneReward {
  const localized = milestoneRewardText[language]?.[reward.id]
  return localized ? { ...reward, ...localized } : reward
}

export function localizeGameAchievement(
  achievement: GameAchievement,
  language: LanguageCode,
): GameAchievement {
  const tier = gameAchievementTierText[language]?.[achievement.tier] ?? gameAchievementTierText.en[achievement.tier]
  return { ...achievement, title: `${achievement.game.title} ${tier}` }
}
